CREATE TABLE auditoria_pedido (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id varchar(255) NOT NULL REFERENCES pedido(id),
  fecha timestamp with time zone NOT NULL,
  evento varchar(50) NOT NULL,
  usuario_id varchar(255) NOT NULL,
  detalle varchar(500)
);
CREATE INDEX auditoria_pedido_fk ON auditoria_pedido(pedido_id);
CREATE TABLE producto_precio_hist (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producto_codigo varchar(255) NOT NULL REFERENCES producto(codigo),
  precio_anterior numeric(14,0) NOT NULL,
  precio_nuevo numeric(14,0) NOT NULL,
  fecha timestamp with time zone NOT NULL
);
CREATE INDEX producto_precio_fk ON producto_precio_hist(producto_codigo);
